#!/usr/bin/env python3
"""Generate Sources/riskell/Themes/Schemes.swift from Base16 YAML files.

Usage: python3 -I scripts/gen-schemes.py [SCHEMES_DIR]

SCHEMES_DIR defaults to the download folder used when the schemes were
fetched. Every id in SCHEME_IDS needs a matching <id>.yaml file there.
Parsing is line-based (no YAML library). Each file must have the top-level
keys system/name/author/variant and all 16 palette slots base00..base0F as
double-quoted #rrggbb values. If any file fails validation, nothing is written.
"""

import os
import re
import sys

# A checkout of https://github.com/tinted-theming/schemes (its base16/ folder), passed as the argument.
DEFAULT_DIR = "schemes/base16"

# Bundled schemes, in menu order. The first entry is the default theme.
SCHEME_IDS = [
    "gruvbox-dark-medium",
    "catppuccin-mocha",
    "rose-pine",
    "nord",
    "tokyo-night-dark",
    "kanagawa",
    "everforest-dark-medium",
    "dracula",
    "github-dark-high-contrast",
    "gruvbox-light-medium",
    "catppuccin-latte",
]

SLOTS = ["base%02X" % i for i in range(16)]  # base00 .. base0F
SLOT_SET = set(SLOTS)

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_PATH = os.path.join(REPO_ROOT, "Sources", "riskell", "Themes", "Schemes.swift")

HEADER = (
    "// Generated by scripts/gen-schemes.py from tinted-theming/schemes (MIT). "
    "Do not edit by hand; see THIRD-PARTY-NOTICES.md."
)

TOP_KEY = re.compile(r"^([A-Za-z_]+)\s*:\s*(.*)$")
SLOT_LINE = re.compile(r"^\s+(base[0-9A-Fa-f]{2})\s*:\s*(.*)$")
QUOTED = re.compile(r'^"((?:[^"\\]|\\.)*)"\s*(#.*)?$')
HEX = re.compile(r"^#[0-9A-Fa-f]{6}$")


class SchemeError(Exception):
    pass



def clean_author(text):
    """Attribution needs names, not contact details: drop e-mail addresses (and the <...> or (...) around them)."""
    t = re.sub(r"\s*[<(][^<>()]*@[^<>()]*[>)]", "", text)
    t = re.sub(r"\S+@\S+", "", t)
    return re.sub(r"\s{2,}", " ", t).strip(" ,")

def unquote_scalar(raw):
    """Value of a top-level scalar: double-quoted, single-quoted, or plain."""
    raw = raw.strip()
    if raw.startswith('"'):
        m = QUOTED.match(raw)
        if not m:
            raise SchemeError("malformed double-quoted value: %s" % raw)
        return re.sub(r"\\(.)", lambda x: x.group(1), m.group(1))
    if raw.startswith("'"):
        m = re.match(r"^'([^']*)'\s*(#.*)?$", raw)
        if not m:
            raise SchemeError("malformed single-quoted value: %s" % raw)
        return m.group(1)
    return re.sub(r"\s+#.*$", "", raw).strip()


def parse_scheme(sid, path):
    top = {}
    palette = {}
    in_palette = False
    with open(path, encoding="utf-8") as fh:
        for lineno, line in enumerate(fh, 1):
            line = line.rstrip("\r\n")
            where = "%s:%d" % (path, lineno)
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            if not line[0].isspace():
                m = TOP_KEY.match(line)
                if not m:
                    raise SchemeError("%s: unrecognised line: %s" % (where, line))
                key, value = m.group(1), m.group(2)
                in_palette = key == "palette"
                if not in_palette:
                    top[key] = unquote_scalar(value) if value.strip() else ""
                continue
            if not in_palette:
                continue
            m = SLOT_LINE.match(line)
            if not m:
                raise SchemeError("%s: unrecognised palette line: %s" % (where, line))
            key = "base" + m.group(1)[4:].upper()
            if key not in SLOT_SET:
                raise SchemeError("%s: unknown slot %s" % (where, m.group(1)))
            if key in palette:
                raise SchemeError("%s: duplicate slot %s" % (where, key))
            vm = QUOTED.match(m.group(2).strip())
            if not vm or not HEX.match(vm.group(1)):
                raise SchemeError('%s: %s must be a double-quoted "#rrggbb"' % (where, key))
            palette[key] = vm.group(1)[1:].lower()  # drop "#"; Swift literal is 0xRRGGBB

    if top.get("system") != "base16":
        raise SchemeError("%s: system must be base16" % path)
    for field in ("name", "author"):
        if not top.get(field):
            raise SchemeError("%s: missing %s" % (path, field))
    if top.get("variant") not in ("dark", "light"):
        raise SchemeError("%s: variant must be dark or light" % path)
    missing = [s for s in SLOTS if s not in palette]
    if missing:
        raise SchemeError("%s: missing slots %s" % (path, ", ".join(missing)))

    return {
        "id": sid,
        "name": top["name"],
        "author": clean_author(top["author"]),
        "variant": top["variant"],
        "palette": palette,
    }


def swift_string(value):
    if any(ord(c) < 0x20 for c in value):
        raise SchemeError("control character in string: %r" % value)
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(schemes):
    lines = [HEADER, "enum BundledSchemes {", "    static let all: [SchemeData] = ["]
    prefix = "        SchemeData("
    pad = " " * len(prefix)
    for s in schemes:
        lines.append(
            "%s"
            "id: %s, name: %s, author: %s, variant: %s,"
            % (
                prefix,
                swift_string(s["id"]),
                swift_string(s["name"]),
                swift_string(s["author"]),
                swift_string(s["variant"]),
            )
        )
        pal = ", ".join('"%s": 0x%s' % (k, s["palette"][k]) for k in SLOTS)
        lines.append(pad + "palette: [" + pal + "]),")
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def main(argv):
    if len(argv) > 2:
        sys.stderr.write("usage: python3 -I scripts/gen-schemes.py [SCHEMES_DIR]\n")
        return 2
    folder = argv[1] if len(argv) == 2 else DEFAULT_DIR

    schemes = []
    try:
        for sid in SCHEME_IDS:
            path = os.path.join(folder, sid + ".yaml")
            if not os.path.isfile(path):
                raise SchemeError("missing scheme file: %s" % path)
            schemes.append(parse_scheme(sid, path))
        text = render(schemes)
    except SchemeError as err:
        sys.stderr.write("gen-schemes: %s\n" % err)
        return 1

    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote %d schemes to %s" % (len(schemes), OUT_PATH))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
