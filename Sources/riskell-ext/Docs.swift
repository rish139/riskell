import Foundation

/// `riskell-ext docs`: `docs/CLI.md`, the command table as markdown. Plain text by construction, so it can be redirected to the file and
/// committed; running it twice writes the same bytes.
enum Docs {
    static func markdown() -> String {
        var out = ["<!-- Generated by `riskell-ext docs` from the command table in Sources/riskell-ext/CommandTable.swift. Do not edit by hand. -->",
                   "",
                   "# risk: the command line",
                   "",
                   "`risk` is how you build, run, check and extend riskell.",
                   "",
                   "This page is generated by `riskell-ext docs` from the command table in `Sources/riskell-ext/CommandTable.swift`; do not edit it by hand.",
                   "Everything below comes from the same table `risk help` and `risk completions` read, so they cannot disagree.",
                   "",
                   "## house rules",
                   ""]
        out += rules.map { "- " + $0 }
        out += ["", "## \(Tier.stable.rawValue)"]
        for row in commandTable where row.tier == .stable {
            out += ["", "### `risk \(row.usage)`", "", row.summary, ""]
            if !row.aliases.isEmpty { out.append("- alias: " + row.aliases.map { "`risk \($0)`" }.joined(separator: ", ")) }
            out.append("- example: `\(row.example)`")
            if !row.otherReplaces.isEmpty { out.append("- replaces: " + row.otherReplaces.map { "`\($0)`" }.joined(separator: ", ")) }
            if !row.children.isEmpty {
                out.append("- subcommands:")
                for child in row.children { out.append("  - `\(child.name)`: \(child.summary)") }
            }
        }
        return out.joined(separator: "\n") + "\n"
    }

    /// The promises the whole command line keeps, independent of any one command.
    private static let rules = [
        "Styled output only on a terminal. A pipe or a file gets plain text, never an escape sequence, so `risk ... | grep` and `$(risk ...)` stay readable.",
        "Every read takes `--json`.",
        "Every writer takes `--dry-run`, and `--yes` where it destroys something.",
        "Exit codes: `0` success, `1` findings or a failed check, `2` bad usage, `10` a rebuild is needed (`risk ext` hands its rebuild to `risk dev`).",
        "Nothing self-updates: `brew upgrade`, then `risk install`.",
        "A `stable` command is removed only with a note in [CHANGELOG.md](../CHANGELOG.md).",
    ]
}
