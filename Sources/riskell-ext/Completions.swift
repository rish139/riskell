import Foundation

/// `risk completions <shell>`: the table as a completion script. Commands, aliases and the subcommands of every group are completed with
/// their one-liners, so pressing tab says what a name does. bash cannot show descriptions; there they are a comment block above the function.
enum Completions {
    /// The script for a shell name, or nil for a shell the table does not know.
    static func script(_ shell: String) -> String? {
        switch shell {
        case "zsh": return zsh
        case "fish": return fish
        case "bash": return bash
        default: return nil
        }
    }

    /// `name:description`, single-quoted for the zsh array and for `_describe`.
    private static func entry(_ name: String, _ summary: String) -> String { quoted("\(name):\(summary)") }

    /// A whole word inside single quotes, apostrophes included.
    private static func quoted(_ text: String) -> String {
        "'" + text.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }

    /// Every name a user can type at the top level: one entry per command, then its aliases. A group's description names its subcommands.
    private static var names: [(name: String, summary: String)] {
        var out: [(name: String, summary: String)] = []
        var seen = Set<String>()
        for row in commandTable where seen.insert(row.name).inserted {
            let children = subcommands(of: row.name)
            out.append((row.name, row.children.isEmpty && !children.isEmpty ? children.map(\.name).joined(separator: ", ") : row.summary))
        }
        out += commandTable.flatMap { row in row.aliases.map { ($0, "another name for \(row.display)") } }
        return out
    }

    /// The groups that have subcommands: `wm`, `gestures`, `config`, `theme`, and `ext` with its declared children.
    private static var groups: [(name: String, children: [Child])] {
        var seen = Set<String>()
        var out: [(name: String, children: [Child])] = []
        for row in commandTable where seen.insert(row.name).inserted {
            let children = subcommands(of: row.name)
            if !children.isEmpty { out.append((row.name, children)) }
        }
        return out
    }

    private static var zsh: String {
        var out = """
        #compdef risk
        # Generated by `riskell-ext completions zsh` from the command table. Do not edit by hand.

        _risk() {
          local -a commands sub

          if (( CURRENT == 2 )); then
            commands=(
        """
        out += "\n"
        for item in names { out += "      \(entry(item.name, item.summary))\n" }
        out += """
            )
            _describe -t commands 'risk command' commands
            return
          fi

          case $words[2] in
        """
        out += "\n"
        for group in groups {
            out += "    \(group.name)) sub=(\(group.children.map { entry($0.name, $0.summary) }.joined(separator: " "))) ;;\n"
        }
        out += """
          esac
          if (( CURRENT == 3 )) && (( ${#sub} )); then
            _describe -t commands "risk $words[2]" sub
          fi
        }

        _risk "$@"

        """
        return out
    }

    private static var fish: String {
        var out = "# Generated by `riskell-ext completions fish` from the command table. Do not edit by hand.\ncomplete -c risk -f\n"
        for item in names {
            out += "complete -c risk -n __fish_use_subcommand -a \(item.name) -d \(quoted(item.summary))\n"
        }
        for group in groups {
            for child in group.children {
                out += "complete -c risk -n \(quoted("__fish_seen_subcommand_from \(group.name)")) -a \(child.name) -d \(quoted(child.summary))\n"
            }
        }
        return out
    }

    private static var bash: String {
        let width = names.map(\.name.count).max() ?? 0
        var out = """
        # Generated by `riskell-ext completions bash` from the command table. Do not edit by hand.
        # bash does not show completion descriptions: they are the comments below.

        """
        out += "\n"
        for item in names {
            out += "#   \(item.name.padding(toLength: width, withPad: " ", startingAt: 0))  \(item.summary)\n"
        }
        out += """

        _risk() {
          local cur sub
          cur=${COMP_WORDS[COMP_CWORD]}
          if [ "$COMP_CWORD" -eq 1 ]; then
            COMPREPLY=( $(compgen -W "\(names.map(\.name).joined(separator: " "))" -- "$cur") )
            return 0
          fi
          case ${COMP_WORDS[1]} in
        """
        out += "\n"
        for group in groups {
            out += "    \(group.name)) sub=\"\(group.children.map(\.name).joined(separator: " "))\" ;;\n"
        }
        out += """
          esac
          if [ "$COMP_CWORD" -eq 2 ] && [ -n "$sub" ]; then
            COMPREPLY=( $(compgen -W "$sub" -- "$cur") )
          fi
        }

        complete -F _risk risk
        """
        return out
    }
}
